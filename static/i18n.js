export function resolveLocale(saved, languages = []) {
  if (supportedLocales.includes(saved)) return saved;
  for (const language of languages) {
    const normalized = String(language).toLowerCase();
    if (normalized === 'zh-tw' || normalized.startsWith('zh-tw-')) return 'zh-TW';
    if (normalized === 'en' || normalized.startsWith('en-')) return 'en';
  }
  return 'zh-CN';
}

function browserLocale() {
  if (typeof window === 'undefined') return 'zh-CN';
  let saved;
  try { saved = window.localStorage.getItem(STORAGE_KEY); } catch {}
  return resolveLocale(saved, [...(window.navigator.languages || []), window.navigator.language]);
}

export const locale = browserLocale();

export function t(key, params = {}, selectedLocale = locale) {
  const template = catalogs[selectedLocale]?.[key] ?? catalogs['zh-CN'][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? `{${name}}`);
}

export function formatDate(value, options = {}) {
  if (!value) return '';
  const date = new Date(value);
  return Number.isNaN(date.valueOf()) ? '' : new Intl.DateTimeFormat(locale, {
    month: 'numeric', day: 'numeric', hour: '2-digit', minute: '2-digit', ...options
  }).format(date);
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach(node => {
    for (const entry of node.dataset.i18nAttr.split(',')) {
      const [attribute, key] = entry.split(':');
      if (attribute && key) node.setAttribute(attribute.trim(), t(key.trim()));
    }
  });
}

export function initI18n(root = document) {
  root.documentElement?.setAttribute('lang', locale);
  applyTranslations(root);
  root.querySelectorAll('.locale-select').forEach(select => {
    select.value = locale;
    select.addEventListener('change', () => {
      try { window.localStorage.setItem(STORAGE_KEY, select.value); } catch {}
      window.location.reload();
    });
  });
}
